import type { RpcEventV0 } from "../adapters/rpc-jsonl/rpc-connection.ts";

type Block = { type: "text"; text: string } | { type: "thinking"; thinking: string; redacted?: boolean };

export const user = (text: string): RpcEventV0 => ({
	type: "message_end",
	record: { message: { role: "user", content: [{ type: "text", text }] } },
});
export const assistant = (content: Block[], stopReason = "stop"): RpcEventV0 => ({
	type: "message_end",
	record: { message: { role: "assistant", stopReason, content } },
});
export const tool = (id: string, name: string, end?: "ok" | "error"): RpcEventV0[] => [
	{ type: "tool_execution_start", record: { toolCallId: id, toolName: name } },
	...(end === undefined
		? []
		: [{ type: "tool_execution_end", record: { toolCallId: id, toolName: name, isError: end === "error" } }]),
];
export const messageStart = (): RpcEventV0 => ({
	type: "message_start",
	record: { message: { role: "assistant", content: [] } },
});
export const thinkingDelta = (index: number, delta: string): RpcEventV0 => ({
	type: "message_update",
	record: { assistantMessageEvent: { type: "thinking_delta", contentIndex: index, delta } },
});
export const textDelta = (index: number, delta: string): RpcEventV0 => ({
	type: "message_update",
	record: { assistantMessageEvent: { type: "text_delta", contentIndex: index, delta } },
});

